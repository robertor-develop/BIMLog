import assert from 'node:assert/strict';
import { previewSamplePurge } from './ga-purge-preview.mjs';
import { APPROVED_SAMPLE_CODES, reconcileSampleAllowlist } from './ga-sample-allowlist.mjs';
import { GA_PROTECTED_PROJECTS } from '../artifacts/api-server/src/lib/ga-protected-projects.ts';
const roster = [...GA_PROTECTED_PROJECTS.map(row => ({ ...row, status: 'active' })), ...APPROVED_SAMPLE_CODES.map((code, i) => ({ id: 10000+i, code, name: 'SYNTHETIC', status: 'archived' })), { id: 20000, code: 'QA-GAUNTLET-1014', name: 'SYNTHETIC', status: 'active' }];
const list = reconcileSampleAllowlist(roster, GA_PROTECTED_PROJECTS);
const graph = { schemaTableCount: 2, completeProjectDependentTables: ['files'] };
const inventory = { rosterSha256: list.rosterSha256, projects: list.candidates.map(row => ({ projectId: row.id, tables: { files: { count: 0, rowIds: [], exportSha256: 'a'.repeat(64) } }, objects: [], auditEvidenceOutsideDeletionScope: true, integrationReferencesVerified: true })) };
const input = { roster, inventory, confirmations: list.candidates, expectedRosterSha256: list.rosterSha256 };
const result = previewSamplePurge(input, graph);
assert.equal(result.readyForIndependentReview, true);
assert.equal(result.executionAuthorized, false);
assert.deepEqual(result.untouchedProjectIds, [23,26,35,20000]);
assert.throws(() => previewSamplePurge({ ...input, expectedRosterSha256: 'stale' }, graph), /STALE/);
assert.throws(() => previewSamplePurge({ ...input, confirmations: [] }, graph), /CONFIRMATIONS/);
assert.equal(previewSamplePurge({ ...input, inventory: { ...inventory, projects: [] } }, graph).readyForIndependentReview, false);
inventory.projects[0].tables.files.count = 2;
assert.equal(result.projects[0].tables.files.count, 0);
inventory.projects[0].tables.files.count = 0;
for (const project of inventory.projects.slice(0,2)) project.objects = [{ objectKey: 'same', ownerProjectIds: [project.projectId], ownershipVerified: true, backupSha256: 'a'.repeat(64), backupReadbackVerified: true }];
assert.throws(() => previewSamplePurge(input, graph), /DUPLICATE_OBJECT/);
console.log('PASS B-GA008 preview: stale identities, incomplete evidence and duplicate storage rejected; execution disabled');
